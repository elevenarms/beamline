import type { Design } from "../types";

// Offline stand-in for POST /api/export/pyopticl: emits a PyOpticL-style layout script.
export function mockPyOpticL(d: Design): string {
  const bp = d.baseplate ?? { width_mm: 300, height_mm: 150, thickness_mm: 25.4, optical_height_mm: 12.7, grid_mm: 25.4 };
  const cls: Record<string, string> = {
    mirror: "optomech.circular_mirror", lens: "optomech.circular_lens", half_wave_plate: "optomech.waveplate",
    quarter_wave_plate: "optomech.waveplate", pbs: "optomech.cube_splitter", beamsplitter: "optomech.cube_splitter",
    sampler: "optomech.circular_sampler", dichroic: "optomech.circular_mirror", aom: "optomech.isomet_1205c_on_km100pm",
    iris: "optomech.pinhole_ida12", fiber_coupler: "optomech.fiberport_mount_hca3", photodiode: "optomech.photodetector_pda10a2",
    beam_dump: "optomech.beam_dump", vapor_cell: "optomech.rb_cell", isolator: "optomech.isolator_670",
  };
  const lines = [
    "# Generated by Beamline (offline mock exporter)",
    "from PyOpticL import layout, optomech",
    "",
    `base_dx = ${(bp.width_mm / 25.4).toFixed(2)} * layout.inch`,
    `base_dy = ${(bp.height_mm / 25.4).toFixed(2)} * layout.inch`,
    `base_dz = ${(bp.thickness_mm / 25.4).toFixed(2)} * layout.inch`,
    "",
    `def ${d.name.replace(/\W+/g, "_")}(x=0, y=0, angle=0):`,
    `    baseplate = layout.baseplate(base_dx, base_dy, base_dz, x=x, y=y, angle=angle, label="${d.name}")`,
  ];
  for (const s of d.sources) {
    lines.push(`    beam_${s.id} = baseplate.add_beam_path(${s.position[0]}, ${s.position[1]}, ${s.direction_deg}, wavelength=${s.wavelength_nm}e-9)`);
  }
  for (const e of d.elements ?? []) {
    const c = cls[e.type] ?? "optomech.circular_mirror";
    const extra = e.focal_length_mm ? `, focal_length=${e.focal_length_mm}` : "";
    if (e.at) {
      lines.push(`    baseplate.place_element("${e.id}", ${c}, x=${e.at[0]}, y=${e.at[1]}, angle=${e.angle_deg ?? 0}${extra})`);
    } else {
      lines.push(`    beam_${(e.beam ?? "").split(".")[0]}.add_element_along_beam("${e.id}", ${c}, ${e.distance_mm}, angle=${e.out_direction_deg ?? e.angle_deg ?? "None"}${extra})  # branch ${e.beam}`);
    }
  }
  lines.push("", "if __name__ == \"__main__\":", `    ${d.name.replace(/\W+/g, "_")}()`, "    layout.redraw()");
  return lines.join("\n");
}
